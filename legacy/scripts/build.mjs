#!/usr/bin/env node
/**
 * Static build.
 *   1. generate the CSS for the bracket window from the measured font contour
 *   2. bundle CSS + client JS (hashed file names)
 *   3. bundle the page code and render every route to dist/<route>/index.html
 *   4. copy the pictures that are actually used, make responsive variants (sharp, optional)
 *   5. sitemap, robots, search.json, catalog.json, IMAGE-SLOTS.md
 *   6. bundle the server
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { build as esbuild } from 'esbuild';
import { loadEnv } from './lib/env.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
loadEnv(ROOT);
const DIST = path.join(ROOT, 'dist');
const PUB = path.join(ROOT, 'public');
const CACHE = path.join(ROOT, '.cache');
const IMG_EXT = /\.(jpe?g|png|webp|avif)$/i;
const argv = process.argv.slice(2);
const REPORT_ONLY = argv.includes('--report-only');
const DEV = process.env.DEV === '1';

const rd = (f, d) => { try { return JSON.parse(fs.readFileSync(f, 'utf8')); } catch { return d; } };
const walk = (dir, base = dir) => !fs.existsSync(dir) ? [] : fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => e.isDirectory() ? walk(path.join(dir, e.name), base) : [path.relative(base, path.join(dir, e.name)).split(path.sep).join('/')]);
const hash = (buf) => crypto.createHash('md5').update(buf).digest('hex').slice(0, 8);
const log = (...a) => console.log('·', ...a);

/* ── 1 · bracket-window css ─────────────────────────────── */
function genBracketCss() {
  const m = rd(path.join(ROOT, 'src/lib/font-metrics.json'));
  const b = m.bracket;
  const pts = (arr, right) => arr.map((k, i) => `${right ? `calc(100% + var(--h) * ${k})` : `calc(var(--h) * ${k})`} ${(b.rows[i] * 100).toFixed(3)}%`);
  const left = pts(b.kLeft, false);
  const right = pts(b.kRight, true).reverse();
  const css = `/* generated by scripts/build.mjs from src/lib/font-metrics.json — do not edit */
.bwin__pic{clip-path:polygon(${left.concat(right).join(',')})}
:root{--k-ink:${b.inkHeightEm};--k-top:${(m.baselineFromTopEm + b.inkTopFromBaselineEm).toFixed(5)};--k-li:${(b.left.innerAtMidEm - b.left.inkLeftEm).toFixed(5)};--k-ll:${b.left.inkLeftEm};--k-rr:${(b.right.inkRightEm - b.right.innerAtMidEm).toFixed(5)};--k-ri:${b.right.innerAtMidEm}}
`;
  fs.mkdirSync(path.join(ROOT, 'src/styles/generated'), { recursive: true });
  fs.writeFileSync(path.join(ROOT, 'src/styles/generated/bwin.css'), css);
  const adv = m.advEm; const total = Object.values(adv).reduce((a, c) => a + c, 0);
  return { total };
}

/* ── 2 · assets ─────────────────────────────────────────── */
async function bundleAssets() {
  fs.mkdirSync(path.join(DIST, 'assets'), { recursive: true });
  const common = { bundle: true, minify: !DEV, write: false, logLevel: 'warning', sourcemap: false, target: ['es2020'] };
  const css = await esbuild({ ...common, entryPoints: [path.join(ROOT, 'src/styles/index.css')], outdir: 'out', loader: { '.woff': 'file', '.woff2': 'file' }, external: ['/fonts/*', '/images/*'] });
  const js = await esbuild({ ...common, entryPoints: [path.join(ROOT, 'src/client/main.ts')], outdir: 'out', format: 'iife' });
  const out = {};
  for (const [res, kind] of [[css, 'css'], [js, 'js']]) {
    const file = res.outputFiles.find((f) => f.path.endsWith('.' + kind));
    const name = `site.${hash(file.contents)}.${kind}`;
    fs.writeFileSync(path.join(DIST, 'assets', name), file.contents);
    out[kind] = '/assets/' + name;
  }
  return out;
}

/* ── 3 · pages ──────────────────────────────────────────── */
async function bundleSsr() {
  const out = path.join(CACHE, 'ssr.mjs');
  await esbuild({
    entryPoints: [path.join(ROOT, 'src/ssr/entry.tsx')], outfile: out, bundle: true, format: 'esm', platform: 'node', packages: 'external',
    jsx: 'automatic', logLevel: 'warning', sourcemap: false, loader: { '.json': 'json' }
  });
  return pathToFileURL(out).href + '?t=' + Date.now();
}

async function imageIndex(sharp) {
  const idxFile = path.join(CACHE, 'image-index.json');
  const cache = rd(idxFile, {});
  const files = walk(path.join(PUB, 'images')).filter((f) => IMG_EXT.test(f) && !f.startsWith('_v/'));
  const dims = {}; const next = {};
  for (const rel of files) {
    const st = fs.statSync(path.join(PUB, 'images', rel));
    const key = `${st.size}-${Math.round(st.mtimeMs)}`;
    if (cache[rel]?.key === key) { dims[rel] = cache[rel].d; next[rel] = cache[rel]; continue; }
    let d = null;
    if (sharp) { try { const m = await sharp(path.join(PUB, 'images', rel)).metadata(); d = { w: m.width, h: m.height }; } catch { /* ignore */ } }
    if (d) { dims[rel] = d; next[rel] = { key, d }; }
  }
  fs.writeFileSync(idxFile, JSON.stringify(next));
  return { files, dims };
}

function slotMaps(files) {
  const local = {}, stripeFiles = {};
  for (const rel of files) {
    if (rel.startsWith('_sample/') || rel.startsWith('_v/')) continue;
    if (rel.startsWith('_stripe/')) { stripeFiles[rel.slice(8).replace(IMG_EXT, '')] = rel; continue; }
    local[rel.replace(IMG_EXT, '')] = rel;
  }
  return { local, stripeFiles };
}

/* ── main ───────────────────────────────────────────────── */
export async function build() {
  const t0 = Date.now();
  fs.mkdirSync(CACHE, { recursive: true });
  const { total } = genBracketCss();

  let sharp = null;
  try { sharp = (await import('sharp')).default; } catch { log('sharp not installed — pictures are served as they are (no responsive variants)'); }
  const { files, dims } = await imageIndex(sharp);
  const { local, stripeFiles } = slotMaps(files);

  if (!REPORT_ONLY) { fs.rmSync(DIST, { recursive: true, force: true }); fs.mkdirSync(DIST, { recursive: true }); }
  const assets = REPORT_ONLY ? { css: '', js: '' } : await bundleAssets();
  log('css + js', assets.css, assets.js);

  const mod = await import(await bundleSsr());
  const { ctx } = mod;
  const stripeCat = rd(path.join(ROOT, 'data/stripe-catalog.json'), { products: {} });
  Object.assign(ctx, {
    mode: ['local', 'stripe', 'strict', 'placeholders'].includes(process.env.IMAGES) ? process.env.IMAGES : 'local',
    demoPrices: process.env.DEMO_PRICES === '1',
    siteUrl: (process.env.SITE_URL || 'http://localhost:3000').replace(/\/$/, ''),
    local, stripeFiles, dims, variants: !!sharp,
    stripe: stripeCat.products || {},
    manualPrices: Object.fromEntries(Object.entries(rd(path.join(ROOT, 'data/prices.json'), {})).filter(([k, v]) => !k.startsWith('_') && typeof v === 'number')),
    assets, dev: DEV, generatedAt: new Date().toISOString(), signTotalEm: total
  });
  // images that live on the Stripe product (when not downloaded)
  for (const [id, e] of Object.entries(ctx.stripe)) (e.images || []).forEach((u, i) => { const s = mod.slotOfProductImage(id, i); if (s) ctx.stripeUrls[s] = u; });
  log('images mode:', ctx.mode, '· demo prices:', ctx.demoPrices, '· stripe products:', Object.keys(ctx.stripe).length, '· local images:', Object.keys(local).length);

  const routes = mod.getRoutes();
  let n = 0;
  for (const r of routes) {
    if (REPORT_ONLY) { ctx.currentPage = r.path; mod.renderRoute(r); n++; continue; }
    const html = mod.renderRoute(r);
    const file = r.path.endsWith('.html') ? path.join(DIST, r.path) : path.join(DIST, r.path, 'index.html');
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, html); n++;
  }
  log('rendered', n, 'pages');

  /* images actually used */
  const used = new Map();
  for (const slot of ctx.usage.keys()) { const r = mod.resolveSlot(slot); if (r.rel) used.set(r.rel, r); }
  if (!REPORT_ONLY) {
    for (const rel of used.keys()) {
      const dst = path.join(DIST, 'images', rel); fs.mkdirSync(path.dirname(dst), { recursive: true });
      fs.copyFileSync(path.join(PUB, 'images', rel), dst);
    }
    if (sharp) {
      const vcache = path.join(CACHE, 'variants'); let made = 0;
      for (const [rel, r] of used) {
        const d = dims[rel]; if (!d) continue;
        const base = rel.replace(IMG_EXT, '');
        for (const w of ctx.variantWidths) {
          if (w >= d.w * 0.92) continue;
          const src = path.join(PUB, 'images', rel); const st = fs.statSync(src);
          const cf = path.join(vcache, `${base}@${w}.webp`); const mk = cf + '.key';
          const key = `${st.size}-${Math.round(st.mtimeMs)}`;
          if (!(fs.existsSync(cf) && fs.existsSync(mk) && fs.readFileSync(mk, 'utf8') === key)) {
            fs.mkdirSync(path.dirname(cf), { recursive: true });
            await sharp(src).rotate().resize({ width: w, withoutEnlargement: true }).webp({ quality: 74, effort: 4 }).toFile(cf);
            fs.writeFileSync(mk, key); made++;
          }
          const dst = path.join(DIST, 'images', '_v', `${base}@${w}.webp`); fs.mkdirSync(path.dirname(dst), { recursive: true }); fs.copyFileSync(cf, dst);
        }
      }
      log('image variants (new):', made);
    }
    fs.cpSync(path.join(PUB, 'fonts'), path.join(DIST, 'fonts'), { recursive: true });
    for (const f of fs.readdirSync(PUB)) if (!['images', 'fonts'].includes(f)) fs.cpSync(path.join(PUB, f), path.join(DIST, f), { recursive: true });
    fs.writeFileSync(path.join(DIST, 'sitemap.xml'), mod.sitemap(routes));
    fs.writeFileSync(path.join(DIST, 'robots.txt'), `User-agent: *\nAllow: /\nDisallow: /api/\nDisallow: /bag/\nSitemap: ${ctx.siteUrl}/sitemap.xml\n`);
    fs.writeFileSync(path.join(DIST, 'search.json'), JSON.stringify(mod.searchIndex(routes)));
    fs.writeFileSync(path.join(DIST, 'catalog.json'), JSON.stringify(mod.publicCatalog()));
  }
  fs.writeFileSync(path.join(ROOT, 'IMAGE-SLOTS.md'), mod.slotsReport(files, dims));
  log('IMAGE-SLOTS.md written');

  if (!REPORT_ONLY) {
    fs.mkdirSync(path.join(ROOT, 'dist-server'), { recursive: true });
    await esbuild({
      entryPoints: [path.join(ROOT, 'server/index.ts')], outfile: path.join(ROOT, 'dist-server/server.mjs'), bundle: true, format: 'esm', platform: 'node',
      target: 'node20', logLevel: 'warning', banner: { js: "import { createRequire as __cr } from 'node:module'; const require = __cr(import.meta.url);" }
    });
    log('server bundled → dist-server/server.mjs');
  }
  if (!REPORT_ONLY) fs.writeFileSync(path.join(DIST, '.stamp'), String(Date.now()));
  log(`done in ${((Date.now() - t0) / 1000).toFixed(1)} s`);
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) build().catch((e) => { console.error(e); process.exit(1); });
